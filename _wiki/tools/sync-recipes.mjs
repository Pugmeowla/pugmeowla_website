// Reads the Infinity mod's crafting and smelting recipes and writes infinity/8.0/data/recipes.mjs for {{recipes}} and the
// item popups. Tinkers' Construct and Tailoring Bench recipes are left out (the armor and items pages describe those).
// Usage: node tools/sync-recipes.mjs <infinity mod folder>
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const modDir = process.argv[2];
if (!modDir) {
  console.error('Usage: node tools/sync-recipes.mjs <infinity mod folder>');
  process.exit(1);
}
const dir = path.join(modDir, 'common/src/main/resources/data/infinity/recipes');

// An ingredient becomes an item ID or "#tag". A list of choices keeps the first one.
const ingredient = (entry) => {
  const one = Array.isArray(entry) ? entry[0] : entry;
  return one.item || `#${one.tag}`;
};
const result = (r) => (typeof r === 'string' ? { out: r, count: 1 } : { out: r.item, count: r.count || 1 });
// Forge mod_loaded conditions, as a short note ("Without Tinkers' Construct").
const NAMES = { tconstruct: "Tinkers' Construct", create: 'Create', fsang: "Fsang's Heropack" };
function note(conditions = []) {
  for (const c of conditions) {
    const not = c.type === 'forge:not';
    const inner = not ? c.value : c;
    if (inner?.type === 'forge:mod_loaded') return `${not ? 'Without' : 'With'} ${NAMES[inner.modid] || inner.modid}`;
  }
  return undefined;
}

const recipes = [];
for (const file of fs.readdirSync(dir).filter((f) => f.endsWith('.json')).sort()) {
  const r = JSON.parse(fs.readFileSync(path.join(dir, file), 'utf8'));
  const id = file.replace(/\.json$/, '');
  if (!['minecraft:crafting_shaped', 'minecraft:crafting_shapeless', 'minecraft:smelting'].includes(r.type)) continue;
  const base = { id, ...result(r.result), note: note(r.conditions) };
  if (r.type === 'minecraft:crafting_shaped') {
    const key = Object.fromEntries(Object.entries(r.key).map(([k, v]) => [k, ingredient(v)]));
    recipes.push({ ...base, type: 'shaped', rows: r.pattern, key });
  } else if (r.type === 'minecraft:crafting_shapeless') {
    recipes.push({ ...base, type: 'shapeless', ingredients: r.ingredients.map(ingredient) });
  } else if (r.type === 'minecraft:smelting') {
    recipes.push({ ...base, type: 'smelting', ingredients: [ingredient(r.ingredient)] });
  }
}
fs.writeFileSync(path.join(here, '../infinity/8.0/data/recipes.mjs'),
  `// Generated by tools/sync-recipes.mjs from the mod's data/infinity/recipes. Ingredients are item IDs or #tags.\n`
  + `export const recipes = [\n${recipes.map((r) => `  ${JSON.stringify(r)},`).join('\n')}\n];\n`);
console.log(`${recipes.length} recipes into infinity/8.0/data/recipes.mjs`);
