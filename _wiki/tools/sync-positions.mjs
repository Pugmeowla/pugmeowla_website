// Reads every stone's skill tree from the Infinity mod's power files and writes infinity/8.0/data/trees.mjs, which the
// {{skilltree}} macro draws. Each visible node with a gui_position is kept: the wiki's own abilities (matched by key, or by
// key + "_dummy") and the tree's dummy entries (the Power Stone's levels and so on), with the parents and cost the game uses.
// Icons that are textures are copied to static/img/tree/.
// Usage: node tools/sync-positions.mjs <infinity mod folder>
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const modDir = process.argv[2];
if (!modDir) {
  console.error('Usage: node tools/sync-positions.mjs <infinity mod folder>');
  process.exit(1);
}
const resources = path.join(modDir, 'common/src/main/resources');
const powers = path.join(resources, 'data/infinity/palladium/powers');
const dataDir = path.join(here, '../infinity/8.0/data');
const imgDir = path.join(here, '../static/img');
const { abilities, groups } = await import(pathToFileURL(path.join(dataDir, 'abilities.mjs')));
const { items } = await import(pathToFileURL(path.join(dataDir, 'items.mjs')));
const lang = JSON.parse(fs.readFileSync(path.join(resources, 'assets/infinity/lang/en_us.json'), 'utf8'));
const text = (t) => (typeof t === 'string' ? t : t?.translate ? lang[t.translate] || '' : t?.text || '');
const clean = (s) => s.replace(/§./g, '').trim();

// A Palladium icon: an item ID (shown with the wiki's picture of that item) or a texture (copied over).
function icon(ref) {
  if (!ref || typeof ref !== 'string') return null;
  const [ns, rest] = ref.split(':');
  if (rest?.startsWith('textures/')) {
    const src = path.join(resources, 'assets', ns, `${rest}`);
    if (!fs.existsSync(src)) return null;
    const name = `${ns}_${path.basename(rest)}`;
    fs.mkdirSync(path.join(imgDir, 'tree'), { recursive: true });
    fs.copyFileSync(src, path.join(imgDir, 'tree', name));
    return `tree/${name}`;
  }
  return items.find((item) => item.id === ref)?.img || null;
}

const trees = {};
const seen = new Set(); // groups sharing a power (Mind Stone and Scepter) get one tree, the first group's
for (const [group, info] of Object.entries(groups)) {
  const file = path.join(powers, `${info.power.split(':')[1]}.json`);
  if (!fs.existsSync(file) || seen.has(info.power)) continue;
  seen.add(info.power);
  const power = JSON.parse(fs.readFileSync(file, 'utf8'));
  if (power.gui_display_type && power.gui_display_type !== 'tree') continue;
  const nodes = [];
  for (const [key, a] of Object.entries(power.abilities || {})) {
    if (a.hidden || !Array.isArray(a.gui_position)) continue;
    const unlocking = a.conditions?.unlocking || [];
    const parents = unlocking.filter((c) => c.type === 'palladium:ability_unlocked').map((c) => c.ability);
    const buy = unlocking.find((c) => c.type === 'palladium:item_buyable');
    const wiki = abilities.find((w) => w.group === group && (w.key === key || `${w.key}_dummy` === key));
    const node = { key, pos: a.gui_position, parents };
    if (wiki) node.ability = wiki.key;
    else {
      node.name = clean(text(a.title)) || key;
      node.summary = clean(text(a.description));
      node.icon = icon(a.icon);
      node.cost = buy ? buy.amount : 0;
    }
    nodes.push(node);
  }
  if (nodes.length) trees[group] = nodes;
}
fs.writeFileSync(path.join(dataDir, 'trees.mjs'), `// Generated by tools/sync-positions.mjs from the mod's power files: every visible skill tree node per group.\n`
  + `// ability: the wiki's ability for that node; otherwise name, summary, icon and cost come from the power file.\n`
  + `export const trees = {\n${Object.entries(trees).map(([g, nodes]) => `  ${g}: [\n${nodes.map((n) => `    ${JSON.stringify(n)},`).join('\n')}\n  ],`).join('\n')}\n};\n`);
const old = path.join(dataDir, 'positions.mjs');
if (fs.existsSync(old)) fs.rmSync(old);
console.log(Object.entries(trees).map(([g, n]) => `${g}: ${n.length}`).join(', '));
